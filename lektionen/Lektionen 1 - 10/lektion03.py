# Lektion 03 - Rechnen mit Zahlen

zahl1       = 20
zahl2       = 6

print("Addition:", zahl1 + zahl2)  # Addition
print("Subtraktion:",zahl1 - zahl2)  # Subtraktion
print("Multiplikation:",zahl1 * zahl2)  # Multiplikation
print("Division:", zahl1 / zahl2)  # Division

print("Ganzzahlige Division:", zahl1 // zahl2)  # Ganzzahlige Division 
print("Modulo:", zahl1 % zahl2)  # Modulo

